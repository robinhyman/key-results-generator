import {
  applyClarifications,
  exploreKeyResultSets,
  generateCausalMetricsGraph,
  indicatorTypeForVariable,
  selectKeyResultVariables,
} from "./generator.js";
import { createOpenAiClient } from "./ai/client.js";
import { defaultKeyResultCount } from "./ai/constants.js";
import { fallbackDiagnostic } from "./ai/errors.js";
import { normalizeObjective } from "./ai/format.js";
import {
  normalizeAiGraph,
  normalizeAiKeyResults,
  normalizeGraphInput,
  relatedDriverLabels,
} from "./ai/normalize.js";
import {
  buildGraphPrompt,
  buildKeyResultsPrompt,
} from "./ai/prompts.js";
import {
  graphResponseSchema,
  keyResultsResponseSchema,
} from "./ai/schemas.js";

export {
  normalizeAiGraph,
  normalizeAiKeyResults,
};

export async function generateAiCausalMetricsGraph(rawObjective, options = {}) {
  const objective = normalizeObjective(rawObjective);
  const fallback = (error) => withGenerationInfo(generateCausalMetricsGraph(objective), {
    mode: "fallback",
    model: "deterministic-local",
    ...fallbackDiagnostic(error, "AI provider unavailable; used the local deterministic generator."),
  });

  return withFallback(async () => {
    const client = await createOpenAiClient(options);
    const response = await client.createJsonResponse({
      operation: "graph",
      schemaName: "causal_metrics_graph",
      schema: graphResponseSchema,
      prompt: buildGraphPrompt(objective),
      validateParsedOutput: (parsedOutput) => normalizeAiGraph(objective, parsedOutput),
    });

    return withGenerationInfo(normalizeAiGraph(objective, response), {
      mode: "ai",
      model: client.model,
      reason: "Generated by the configured AI provider.",
    });
  }, fallback);
}

export async function generateAiKeyResultsModel(graph, clarifications = {}, options = {}) {
  const normalizedGraph = normalizeGraphInput(graph) ?? generateCausalMetricsGraph("");
  const clarifiedGraph = applyClarifications(normalizedGraph, clarifications);
  const fallback = (error) => {
    const keyResults = selectKeyResultVariables(clarifiedGraph.rankings, defaultKeyResultCount, clarifiedGraph).map((variable, index) =>
      toFallbackKeyResult(variable, clarifiedGraph.edges, clarifiedGraph.nodes, index, clarifiedGraph.assessments[variable.id]),
    );

    return withModelGenerationInfo(toModel(clarifiedGraph, keyResults), {
      mode: "fallback",
      model: "deterministic-local",
      ...fallbackDiagnostic(error, "AI provider unavailable; used the local deterministic KR synthesizer."),
    });
  };

  return withFallback(async () => {
    const client = await createOpenAiClient(options);
    const response = await client.createJsonResponse({
      operation: "key-results",
      schemaName: "key_results",
      schema: keyResultsResponseSchema,
      prompt: buildKeyResultsPrompt(clarifiedGraph),
      validateParsedOutput: (parsedOutput) => normalizeAiKeyResults(clarifiedGraph, parsedOutput),
    });
    const keyResults = normalizeAiKeyResults(clarifiedGraph, response);

    return withModelGenerationInfo(toModel(clarifiedGraph, keyResults), {
      mode: "ai",
      model: client.model,
      reason: "Synthesized by the configured AI provider from the graph and user clarifications.",
    });
  }, fallback);
}

async function withFallback(action, fallback) {
  try {
    return await action();
  } catch (error) {
    return fallback(error);
  }
}

function toModel(graph, keyResults) {
  const candidateKeyResultSets = exploreKeyResultSets(graph);

  return {
    objective: graph.objective,
    summary: graph.summary,
    graph,
    variables: graph.nodes,
    relationships: graph.edges,
    rankedVariables: graph.rankings,
    candidateKeyResultSets,
    keyResults,
  };
}

function withGenerationInfo(graph, generation) {
  return { ...graph, generation };
}

function withModelGenerationInfo(model, generation) {
  return {
    ...model,
    generation,
    graph: withGenerationInfo(model.graph, generation),
  };
}

function toFallbackKeyResult(variable, relationships, variables, index, assessment) {
  const relatedDrivers = relatedDriverLabels(variable.id, { edges: relationships, nodes: variables });
  const phrase = variable.direction === "reduce"
    ? `Reduce ${variable.label} by 20% in the next 90 days`
    : variable.direction === "increase"
      ? `Increase ${variable.label} by 15% in the next 90 days`
      : `Improve ${variable.label} to a clearly measured green status in the next 90 days`;
  const clarificationContext = assessment
    ? ` Your clarification rated it ${assessment.influenceability}/5 for influenceability and ${assessment.gap}/5 for perceived gap.`
    : "";

  return {
    id: `kr-${index + 1}`,
    variableId: variable.id,
    indicatorType: indicatorTypeForVariable(variable),
    text: phrase,
    rationale: `${variable.label} remains a strong candidate in the clarified causal model.${clarificationContext}`,
    relatedDrivers,
    score: variable.score,
    assessment: assessment ?? null,
  };
}
